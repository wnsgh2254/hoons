#!/usr/bin/env python3
"""
One-off: set public.customers.id to legacy shop customer numbers from Excel column B (e.g. ="4304"),
matching rows by normalized phone (column D landline, then E mobile).

Requires a direct Postgres connection (REST cannot rewrite PK / identity).
  pip install psycopg[binary] requests openpyxl
  Set DATABASE_URL in haeyoom/.env.local (Session mode URI from Supabase Dashboard -> Connect).

Flow (single transaction):
  LOCK TABLE customers
  ALTER COLUMN id DROP IDENTITY IF EXISTS
  UPDATE customers SET id = new_id FROM mapping (by old id)
  ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY
  setval(sequence, max(id))

Run with --dry-run first. Comments in English.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
from pathlib import Path
from typing import Dict, List, Optional, Tuple

import requests

from import_customers_from_file import (
    list_customer_shop_excel_files,
    merge_rows_from_excel_files,
    normalize_phone,
)
from import_sales_from_file import load_env_file

MIGRATIONS_DIR = Path(__file__).resolve().parent
PROJECT_ROOT = MIGRATIONS_DIR.parents[1]
ENV_PATH = PROJECT_ROOT / ".env.local"


def digits_only(val: object) -> str:
    return re.sub(r"\D", "", str(val or "").strip())


def load_phone_to_legacy_from_workbooks(folder: Path) -> Tuple[Dict[str, int], Dict[str, int]]:
    """
    phone_digits -> legacy_id. merge_rows_from_excel_files keeps first row per phone.
    Returns (mapping, stats with phone_conflicts from merge).
    """
    paths = list_customer_shop_excel_files(folder)
    if not paths:
        raise RuntimeError(f"No '고객 정보*_shop_*.xlsx' files under {folder}")
    merged, stats = merge_rows_from_excel_files(paths)
    out: Dict[str, int] = {}
    for customer_number, _name, mobile_raw, tel_raw in merged:
        if customer_number is None:
            continue
        phone = normalize_phone(tel_raw) or normalize_phone(mobile_raw)
        if not phone:
            continue
        out[phone] = int(customer_number)
    return out, stats


def fetch_all_customers(url: str, key: str) -> List[dict]:
    headers = {"apikey": key, "Authorization": f"Bearer {key}"}
    base = url.rstrip("/")
    out: List[dict] = []
    start = 0
    page = 1000
    while True:
        r = requests.get(
            f"{base}/rest/v1/customers?select=id,phone&offset={start}&limit={page}",
            headers=headers,
            timeout=120,
        )
        r.raise_for_status()
        rows = r.json()
        if not rows:
            break
        out.extend(rows)
        if len(rows) < page:
            break
        start += page
    return out


def build_remap_pairs(
    phone_to_legacy: Dict[str, int], customers: List[dict]
) -> Tuple[List[Tuple[int, int]], List[dict], dict]:
    """
    Returns (pairs (old_id, new_id), conflicts same legacy two phones), summary dict.
    """
    raw: List[Tuple[int, int, str]] = []
    for c in customers:
        ph = digits_only(c.get("phone"))
        if not ph or ph not in phone_to_legacy:
            continue
        legacy = phone_to_legacy[ph]
        oid = int(c["id"])
        if oid == legacy:
            continue
        raw.append((oid, legacy, ph))

    chosen: Dict[int, Tuple[int, str]] = {}
    conflicts: List[dict] = []
    for oid, nid, ph in raw:
        if nid not in chosen:
            chosen[nid] = (oid, ph)
            continue
        prev_oid, prev_ph = chosen[nid]
        conflicts.append(
            {
                "legacy_id": nid,
                "kept_old_id": prev_oid,
                "kept_phone": prev_ph,
                "skipped_old_id": oid,
                "skipped_phone": ph,
            }
        )
    pairs = [(chosen[nid][0], nid) for nid in sorted(chosen.keys())]
    old_set = {a for a, _ in pairs}
    new_set = {b for _, b in pairs}
    all_ids = {int(c["id"]) for c in customers}
    danger = new_set & all_ids - old_set
    summary = {
        "rows_to_remap": len(pairs),
        "phones_in_workbook": len(phone_to_legacy),
        "legacy_id_conflicts_skipped": len(conflicts),
        "danger_target_id_held_by_other_row": sorted(danger),
    }
    return pairs, conflicts, summary


def run_sql_transaction(dsn: str, pairs: List[Tuple[int, int]], chunk_size: int = 400) -> None:
    try:
        import psycopg
    except ImportError as e:
        raise RuntimeError(
            "Install psycopg: pip install 'psycopg[binary]'"
        ) from e

    conn = psycopg.connect(dsn, autocommit=False)
    try:
        with conn.cursor() as cur:
            cur.execute("lock table public.customers in access exclusive mode;")
            cur.execute("alter table public.customers alter column id drop identity if exists;")
            for i in range(0, len(pairs), chunk_size):
                chunk = pairs[i : i + chunk_size]
                vals = ",".join(f"({a}::bigint,{b}::bigint)" for a, b in chunk)
                cur.execute(
                    f"""
                    update public.customers c
                    set id = m.new_id
                    from (values {vals}) as m(old_id, new_id)
                    where c.id = m.old_id;
                    """
                )
            cur.execute(
                "alter table public.customers alter column id "
                "add generated by default as identity;"
            )
            cur.execute(
                """
                select setval(
                  pg_get_serial_sequence('public.customers', 'id'),
                  (select coalesce(max(id), 1) from public.customers)
                );
                """
            )
        conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--excel-dir",
        type=Path,
        default=MIGRATIONS_DIR,
        help="Folder containing 고객 정보*_shop_*.xlsx workbooks (default: this migrations folder)",
    )
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()

    env = load_env_file(ENV_PATH)
    url = os.getenv("SUPABASE_URL") or env.get("SUPABASE_URL")
    key = os.getenv("SUPABASE_SERVICE_ROLE_KEY") or env.get("SUPABASE_SERVICE_ROLE_KEY")
    dsn = os.getenv("DATABASE_URL") or env.get("DATABASE_URL")

    if not url or not key:
        print("Missing SUPABASE_URL or SUPABASE_SERVICE_ROLE_KEY", file=sys.stderr)
        return 1

    phone_to_legacy, merge_stats = load_phone_to_legacy_from_workbooks(args.excel_dir)
    customers = fetch_all_customers(url, key)
    pairs, conflicts, summary = build_remap_pairs(phone_to_legacy, customers)

    summary["excel_phone_conflicts"] = merge_stats.get("phone_conflicts", 0)
    print(json.dumps(summary, indent=2, ensure_ascii=False))
    if conflicts:
        p = MIGRATIONS_DIR / "_customer_id_remap_conflicts.json"
        p.write_text(json.dumps(conflicts, indent=2, ensure_ascii=False), encoding="utf-8")
        print(f"[WARN] Wrote {p} ({len(conflicts)} legacy collisions)")

    if summary["danger_target_id_held_by_other_row"]:
        print(
            "[FATAL] Target id(s) already used by a row not in remap set — aborting.",
            file=sys.stderr,
        )
        return 1

    if not pairs:
        print("[INFO] Nothing to remap.")
        return 0

    if args.dry_run:
        print("[INFO] Dry run; first 5 pairs:", pairs[:5])
        return 0

    if not dsn:
        print(
            "Missing DATABASE_URL in environment or .env.local.\n"
            "Supabase Dashboard -> Connect -> Session pooler URI (postgres.xxx).\n"
            "Example: DATABASE_URL=postgresql://postgres.[ref]:[password]@aws-0-[region].pooler.supabase.com:5432/postgres",
            file=sys.stderr,
        )
        return 1

    run_sql_transaction(dsn, pairs)
    print("[DONE] customers.id remap committed (identity restored + setval).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
