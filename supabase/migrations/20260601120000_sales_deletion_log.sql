-- Audit log when staff delete a sale (no UI; query-only).
CREATE TABLE IF NOT EXISTS public.sales_deletion_log (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sale_id bigint NOT NULL,
  booking_id bigint,
  sales_date date NOT NULL,
  sales_time text,
  designer_name text,
  customer_name text,
  cash_amount numeric NOT NULL DEFAULT 0,
  card_amount numeric NOT NULL DEFAULT 0,
  bank_transfer_amount numeric NOT NULL DEFAULT 0,
  prepaid_amount numeric NOT NULL DEFAULT 0,
  total_amount numeric NOT NULL DEFAULT 0,
  payment_method text,
  deposit_paid numeric NOT NULL DEFAULT 0,
  deleted_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS sales_deletion_log_deleted_at_idx
  ON public.sales_deletion_log (deleted_at DESC);

CREATE INDEX IF NOT EXISTS sales_deletion_log_sales_date_idx
  ON public.sales_deletion_log (sales_date DESC);

COMMENT ON TABLE public.sales_deletion_log IS 'Append-only log when a sale is deleted from admin; booking is kept and sale_completed is cleared.';
