import { test, expect, request as playwrightRequest } from '@playwright/test';

async function gotoSettings(page: import('@playwright/test').Page) {
  await page.goto('/admin/settings', { waitUntil: 'domcontentloaded' });
  await page.getByRole('heading', { name: '??' }).waitFor({ state: 'visible', timeout: 15000 });
}

// ??? API ?? ?? ???????????????????????????????????????????????????????????

test.describe('[API] ?? ?? API ??', () => {
  let api: Awaited<ReturnType<typeof playwrightRequest.newContext>>;

  test.beforeAll(async () => { api = await playwrightRequest.newContext({ baseURL: 'http://localhost:3000' }); });
  test.afterAll(async () => { await api.dispose(); });

  test('? ?? API ? 200 ?? + shops ??', async () => {
    const res = await api.get('/api/shops');
    expect(res.status()).toBe(200);
    const body = await res.json();
    expect(body).toHaveProperty('shops');
    expect(Array.isArray(body.shops)).toBeTruthy();
  });

  test('? ?? API ? ? ?? id, name? ??? ?', async () => {
    const res = await api.get('/api/shops');
    const body = await res.json();
    if (body.shops.length > 0) {
      expect(body.shops[0]).toHaveProperty('id');
      expect(body.shops[0]).toHaveProperty('name');
    }
  });

  test('?? ?? ?? API ? ?? ??', async () => {
    const res = await api.get('/api/booking-restrictions');
    expect([200, 404]).toContain(res.status());
  });

  test('?? ?? API ? ??? ?? ??', async () => {
    const res = await api.get('/api/auth/session');
    expect(res.status()).toBe(200);
    const body = await res.json();
    expect(body.authenticated).toBeTruthy();
    expect(body.user?.role).toBe('director');
  });

  test('??? API ? ?? ???? ???? ??? ??', async () => {
    const res = await api.get('/api/services');
    expect(res.status()).toBe(200);
    const body = await res.json();
    expect(body.services.length).toBeGreaterThan(0);
  });
});

